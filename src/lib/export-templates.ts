/**
 * Export templates for docker-compose.yml, Dockerfile, and README for dynamic designs
 */

export function generateDockerCompose(mode: 'dev' | 'prod' = 'prod', port = 3000, designId?: string): string {
  if (mode === 'dev') {
    // Development mode: volume mount, hot reload
    // For DooD architecture: mount the shared designs volume and reference specific design subfolder
    const workingDir = designId ? `/designs/${designId}` : '/app';
    const volumeMount = designId ? 'react_compoment_generator_designs-data:/designs' : '.:/app';

    return `# Generated by React Component Generator - Development Mode
# Run: docker compose up
version: '3.8'

services:
  app:
    image: node:20-alpine
    working_dir: ${workingDir}
    ports:
      - "0.0.0.0:${port}:3000"
    environment:
      - DATABASE_URL=postgresql://postgres:devpassword@db:5432/app
      - NODE_ENV=development
    volumes:
      - ${volumeMount}
      - node_modules:${workingDir}/node_modules
      - nextjs_cache:${workingDir}/.next
    command: sh -c "npm install && (npx prisma generate 2>/dev/null || echo 'No Prisma models, skipping') && (npx prisma migrate deploy 2>/dev/null || echo 'No migrations, skipping') && npm run dev"
    depends_on:
      db:
        condition: service_healthy

  db:
    image: postgres:16-alpine
    environment:
      - POSTGRES_PASSWORD=devpassword
      - POSTGRES_DB=app
    volumes:
      - pgdata:/var/lib/postgresql/data
    healthcheck:
      test: ["CMD-SHELL", "pg_isready -U postgres"]
      interval: 5s
      timeout: 5s
      retries: 5

volumes:
  ${designId ? 'react_compoment_generator_designs-data:\n    external: true\n  ' : ''}node_modules:
  nextjs_cache:
  pgdata:
`;
  }

  // Production mode: build from Dockerfile
  return `# Generated by React Component Generator
# Run: docker compose up
version: '3.8'

services:
  app:
    build:
      context: .
      dockerfile: Dockerfile
    ports:
      - "3000:3000"
    environment:
      - DATABASE_URL=postgresql://postgres:postgres@db:5432/app
      - NODE_ENV=production
    depends_on:
      db:
        condition: service_healthy

  db:
    image: postgres:16-alpine
    environment:
      - POSTGRES_PASSWORD=postgres
      - POSTGRES_DB=app
    volumes:
      - pgdata:/var/lib/postgresql/data
    healthcheck:
      test: ["CMD-SHELL", "pg_isready -U postgres"]
      interval: 5s
      timeout: 5s
      retries: 5

volumes:
  pgdata:
`;
}

export function generateDockerfile(): string {
  return `FROM node:20-alpine

WORKDIR /app

# Copy package files
COPY package.json ./

# Install dependencies
RUN npm install

# Copy all source files
COPY . .

# Generate Prisma Client
RUN npx prisma generate

# Build Next.js app
RUN npm run build

EXPOSE 3000

# Run migrations and start production server
CMD ["sh", "-c", "npx prisma migrate deploy && npm start"]
`;
}

